"""Sweep the explicit-threat override threshold (threat_override_p) on the VALIDATION world only.

For each value the validation world is replayed message by message with the fitted risk model
(models/risk_model.json); only threat_override_p changes. Reported per value:
  - harasser pairs detected (reach High at any point) and median sessions to detect
  - false-alarm pairs / rate (non-harasser pairs that ever reach High)
  - false alarms caused only by the override (vs. the "never" setting)
  - safety: share of pairs that received a Jigsaw-labelled threat message and were at High
    within threat_hold_hours of the first such message
The test worlds are never touched. Writes reports/override_tuning.json and reports/override_tuning.md.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
from bae.config import REPORTS, EngineConfig  # noqa: E402
from bae.experiment import replay  # noqa: E402
from evaluate import streaming  # noqa: E402
from fit_risk_model import BASE_TS, load  # noqa: E402

GRID = [0.90, 0.93, 0.95, 0.97, 0.99, None]  # None = never (override disabled)


def threat_safety(df, rep, hold_hours: float) -> dict:
    """Pairs that received a labelled threat: were they at >= High within the hold window?"""
    thr = df[df.bucket == "threat"].groupby(["sender", "target"]).ts.min()
    ok = sum(1 for k, t0 in thr.items() if k in rep["first_high"] and rep["first_high"][k][0] <= t0 + hold_hours * 3600)
    return {"pairs_with_labelled_threat": int(len(thr)), "alerted_within_hold": ok,
            "share_alerted_within_hold": round(ok / max(1, len(thr)), 4)}


def main():
    base = EngineConfig.load()
    df, pairs = load("val")
    # T and p_threat in the synthetic worlds come from the scorer generate_synthetic.py loads ("auto")
    from bae.content_model import load_scorer
    content_model = load_scorer("auto").name
    rows, reps = [], {}
    for p in GRID:
        cfg = EngineConfig(**{**base.__dict__, "threat_override_p": 1.01 if p is None else p})
        rep = replay(df, cfg, [], base_ts=BASE_TS)
        reps[p] = rep
        eng = streaming(df, pairs, rep, cfg)["engine"]
        rows.append({"threat_override_p": "never" if p is None else p, **eng,
                     **threat_safety(df, rep, cfg.threat_hold_hours)})
        print(rows[-1])
    pos = set(map(tuple, pairs[pairs.label == 1][["sender", "target"]].values))
    never_high = set(reps[None]["first_high"])
    for r, p in zip(rows, GRID):
        only = [k for k in reps[p]["first_high"] if k not in pos and k not in never_high]
        trig = df[(df.p_threat >= (1.01 if p is None else p)) & (df.bucket == "threat")]
        real = set(map(tuple, trig[["sender", "target"]].values))
        r["override_only_false_alarms"] = len(only)
        r["override_only_with_labelled_threat"] = sum(1 for k in only if k in real)

    out = {"world": "synthetic_val (validation only; test worlds untouched)", "content_model_scores": content_model,
           "positives": len(pos), "negatives": int(len(pairs) - len(pos)),
           "threat_hold_hours": base.threat_hold_hours, "current_threat_override_p": base.threat_override_p,
           "rows": rows}
    (REPORTS / "override_tuning.json").write_text(json.dumps(out, indent=2, default=float), encoding="utf-8")

    L = ["# Explicit-threat override sweep (validation world only)\n",
         f"{out['positives']} harasser pairs and {out['negatives']:,} other pairs in `synthetic_val`. "
         f"Hold window {base.threat_hold_hours:g} h. Current setting: threat_override_p = {base.threat_override_p}.\n",
         "| threat_override_p | Harasser pairs detected | Median sessions to detect | False-alarm pairs | False-alarm rate "
         "| of which override-only (with a labelled threat) | Labelled-threat pairs at High within hold |",
         "|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['threat_override_p']} | {r['harasser_pairs_detected']:.1%} | {r['median_sessions_to_detect']} | "
                 f"{r['false_alarm_pairs']:,} | {r['false_alarm_rate']:.2%} | "
                 f"{r['override_only_false_alarms']:,} ({r['override_only_with_labelled_threat']:,}) | "
                 f"{r['alerted_within_hold']}/{r['pairs_with_labelled_threat']} ({r['share_alerted_within_hold']:.1%}) |")
    L.append("\nGenerated by `python scripts/tune_override.py`.")
    (REPORTS / "override_tuning.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
